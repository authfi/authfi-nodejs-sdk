#!/usr/bin/env node
// Generates src/core/codes.ts: the token refusal codes of the AuthFI kernel at a pinned tag, so the
// verifier in this SDK speaks the platform's vocabulary and never a second spelling of it.
//
//   node scripts/gen-codes.mjs --kernel <path to a checkout of the AuthFI kernel> [--ref v0.58.0]
//       reads the kernel's constants at the ref (git show), and writes the file.
//   node scripts/gen-codes.mjs --check [--kernel <path>]
//       without --kernel: checks the committed file was not edited by hand (its digest line).
//       with --kernel: also regenerates and fails when the kernel's list differs.
//
// A pull-request job runs the first form of --check, and the weekly drift job, which can read the
// kernel, runs the second.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DEFAULT_REF = 'v0.58.0';
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'codes.ts');

function arg(name) {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
}

function step(message) {
  process.stdout.write(`gen-codes: ${message}\n`);
}

function fail(message) {
  process.stderr.write(`gen-codes: FAILED: ${message}\n`);
  process.exit(1);
}

function readAt(kernel, ref, path) {
  return execFileSync('git', ['-C', kernel, 'show', `${ref}:${path}`], { encoding: 'utf8' });
}

/** Every string constant in the source whose value starts with one of the prefixes. */
function constants(source, prefixes) {
  const out = new Set();
  for (const m of source.matchAll(/=\s*"([a-z0-9_]+)"/g)) {
    const value = m[1];
    if (prefixes.some((p) => value.startsWith(p))) out.add(value);
  }
  return [...out].sort();
}

function digest(codes) {
  return createHash('sha256').update(codes.join('\n')).digest('hex');
}

function render(ref, codes) {
  const lines = codes.map((c) => `  '${c}',`).join('\n');
  return `// GENERATED by scripts/gen-codes.mjs from the AuthFI kernel at ${ref}.
// Do not edit: run \`npm run gen:codes -- --kernel <path>\`.
// digest: ${digest(codes)}

/**
 * The kernel's token refusal codes (\`token_*\`) and DPoP proof reasons (\`dpop_*\`), as of
 * the AuthFI kernel at ${ref}. A platform log line, audit record or SDK \`InvalidToken\` carries one.
 */
export const KERNEL_TOKEN_CODES = [
${lines}
] as const;

/** One of {@link KERNEL_TOKEN_CODES}. */
export type KernelTokenCode = (typeof KERNEL_TOKEN_CODES)[number];

/** The kernel tag the codes were read from. */
export const KERNEL_CODES_REF = '${ref}';
`;
}

function committedCodes() {
  const text = readFileSync(OUT, 'utf8');
  const recorded = /^\/\/ digest: ([0-9a-f]{64})$/m.exec(text)?.[1];
  const ref = /^export const KERNEL_CODES_REF = '([^']+)';$/m.exec(text)?.[1];
  const codes = [...text.matchAll(/^ {2}'([a-z0-9_]+)',$/gm)].map((m) => m[1]);
  return { recorded, ref, codes };
}

const kernel = arg('--kernel');
const check = process.argv.includes('--check');

if (check) {
  step(`checking ${OUT}`);
  const { recorded, ref, codes } = committedCodes();
  if (!recorded || !ref) fail('the file has no digest or ref line; regenerate it');
  if (digest(codes) !== recorded)
    fail('the code list does not match its digest: the file was edited by hand');
  step(`digest matches (${codes.length} codes from ${ref})`);
  if (kernel) {
    const fresh = generate(kernel, arg('--ref') ?? ref);
    if (fresh.join('\n') !== codes.join('\n')) {
      const added = fresh.filter((c) => !codes.includes(c));
      const removed = codes.filter((c) => !fresh.includes(c));
      fail(`the kernel's list differs: added [${added.join(', ')}], removed [${removed.join(', ')}]`);
    }
    step('the kernel agrees');
  } else {
    step('no --kernel given: the kernel comparison runs in the weekly drift job');
  }
} else {
  if (!kernel) fail('--kernel <path to a checkout of the AuthFI kernel> is required');
  const ref = arg('--ref') ?? DEFAULT_REF;
  const codes = generate(kernel, ref);
  writeFileSync(OUT, render(ref, codes));
  step(`wrote ${codes.length} codes from ${ref} to ${OUT}`);
}

function generate(path, ref) {
  step(`reading constants/http.go and dpop/dpop.go at ${ref}`);
  const tokenCodes = constants(readAt(path, ref, 'constants/http.go'), ['token_']);
  const dpopCodes = constants(readAt(path, ref, 'dpop/dpop.go'), ['dpop_']);
  if (tokenCodes.length === 0) fail(`no token_ codes found at ${ref}`);
  return [...tokenCodes, ...dpopCodes];
}
